_TERMS: List[Term] = [
    Term(key=r[0], term=r[1], data_type=r[2], plain_language=r[3], how_to_read=r[4],
         common_misunderstanding=r[5], applicable_horizons=tuple(r[6]),
         not_applicable_to=tuple(r[7]) if len(r) > 7 else (),
         system_role=ENGINE_USAGE.get(r[0], ("INFO", ()))[0],
         used_by_engine_horizons=tuple(ENGINE_USAGE.get(r[0], ("INFO", ()))[1]))
    for r in _ROWS
]

GLOSSARY: Dict[str, Term] = {t.key: t for t in _TERMS}


def get(key: str) -> Term:
    return GLOSSARY[key]


def tooltip(key: str) -> str:
    """給 UI ⓘ 用的短說明：白話＋怎麼看。"""
    t = GLOSSARY[key]
    return f"{t.term}：{t.plain_language}。{t.how_to_read}"


def by_horizon(horizon: str) -> List[Term]:
    return [t for t in _TERMS if horizon in t.applicable_horizons]


def is_applicable(key: str, asset: str) -> bool:
    """概念上是否適用這種商品（例如 EPS 對 ETF 不適用）。"""
    return asset not in GLOSSARY[key].not_applicable_to


def used_by_engine(key: str, horizon: str) -> bool:
    """本站目前是否在這個週期使用（跟「適不適用」無關）。"""
    return horizon in GLOSSARY[key].used_by_engine_horizons


def all_terms() -> List[Term]:
    return list(_TERMS)
